import fs from 'node:fs/promises';
import { Workbook, SpreadsheetFile } from '@oai/artifact-tool';
const out = '/Users/brianeichenberger/projects/the_swell/swell_website/swell-parts/outputs/01a0ecfd-f705-74c1-b3f4-ee42330d3149';
const w = Workbook.create();
const s = w.worksheets.add('Audio inputs');
const sources = ['Joe vocal','Chris vocal','Ike vocal','Jackson vocal','Sam vocal','Cello','Joe gtr','Keyboard A','Keyboard B','Bass','Acoustic gtr','Jackson gtr','Sax','Drums - kick','Drums - hat/snare','Drums - overhead'];
s.getRange('A1').values = [['THE SWELL — Audio input list']];
s.getRange('A2').values = [['Updated September 30, 2026']];
s.getRange('A4:C20').values = [['Channel','Source','DI required'], ...sources.map((name,i)=>[i+1,name,i>=5&&i<=12?'Yes':'No'])];
s.getRange('A1:C20').format.font = { name:'Arial',size:12,color:'#000000' };
s.getRange('A1:C20').format.verticalAlignment='center';
s.getRange('A1:C20').format.rowHeight=24;
s.getRange('A1').format.font={name:'Arial',size:17,bold:true,color:'#000000'};
s.getRange('A2').format.font={name:'Arial',size:10,color:'#555555'};
s.getRange('A4:C4').format={fill:'#EEEEEE',font:{name:'Arial',size:12,bold:true,color:'#000000'},horizontalAlignment:'center'};
s.getRange('A5:A20').format.horizontalAlignment='center';
s.getRange('C5:C20').format.horizontalAlignment='center';
s.getRange('A1:A20').format.columnWidthPx=90;
s.getRange('B1:B20').format.columnWidthPx=280;
s.getRange('C1:C20').format.columnWidthPx=165;
s.getRange('A5:C20').format.borders={insideHorizontal:{style:'thin',color:'#E5E5E5'}};
s.getRange('C5:C20').dataValidation={rule:{type:'list',values:['Yes','No']}};
s.freezePanes.freezeRows(4);
w.recalculate();
console.log((await w.inspect({kind:'table',range:"'Audio inputs'!A4:C20",include:'values',tableMaxRows:20,tableMaxCols:3,maxChars:4000})).ndjson);
const png=await w.render({sheetName:'Audio inputs',range:'A1:C20',scale:2,format:'png'});
await fs.writeFile(out+'/input-list-preview.png',new Uint8Array(await png.arrayBuffer()));
await (await SpreadsheetFile.exportXlsx(w)).save(out+'/the-swell-audio-inputs.xlsx');
