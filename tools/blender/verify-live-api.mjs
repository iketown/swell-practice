// Checks only the isolated setup created by prepare-integration-check.mjs.
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { randomUUID } from 'node:crypto';
import { getServerFirestore } from '@/lib/server/firebase-admin';
const connection = JSON.parse(readFileSync('tmp/blender-integration/connection.json', 'utf8'));
assert.equal(connection.setupId, 'blender-integration-check-20260907');
const endpoint = `${connection.appUrl}/api/setups/${connection.setupId}/blender-items`;
const headers = { Authorization: `Swell ${connection.token}`, 'Content-Type': 'application/json' };
const response = await fetch(endpoint, { headers }); assert.equal(response.status, 200);
const snapshot = await response.json();
assert.equal(snapshot.items.length, 1);
const template = (await getServerFirestore().doc('equipmentTemplates/blender-integration-box-20260907').get()).data();
assert.equal(template.version, 2);
assert.ok(Math.abs(template.physicalDimensions.widthInches - 36) < 0.001);
assert.ok(Math.abs(template.physicalDimensions.heightInches - 12) < 0.001);
const patch = { schemaVersion: 1, setupId: connection.setupId, baseRevision: snapshot.revision, clientId: randomUUID(), mutationId: randomUUID(), changes: [{ nodeId: 'verification-box', pose: { elevationMeters: 0.1 } }] };
const send = (body) => fetch(endpoint, { method: 'PATCH', headers, body: JSON.stringify(body) });
const first = await send(patch); assert.equal(first.status, 200); const ack = await first.json();
const replay = await send(patch); assert.equal(replay.status, 200); assert.equal((await replay.json()).replayed, true);
assert.equal((await send({ ...patch, mutationId: randomUUID() })).status, 409);
assert.equal((await send({ ...patch, changes: [{ nodeId: 'verification-box', pose: { elevationMeters: 0.2 } }] })).status, 409);
assert.equal((await fetch(endpoint)).status, 401);
assert.equal((await fetch(endpoint.replace(connection.setupId, 'QWSok55nO20JC3B8WL0x'), { headers })).status, 403);
const bad = await fetch(`${connection.appUrl}/api/setups/${connection.setupId}/blender-sessions`, { method: 'POST', headers: { 'x-swell-demo': '1', 'Content-Type': 'application/json', origin: connection.appUrl }, body: JSON.stringify({ allowDefinitions: true }) });
assert.equal(bad.status, 401);
const report = { passed: ['dimension correction persisted on definition', 'idempotent replay', 'stale revision rejected', 'changed-payload replay rejected', 'unauthenticated rejected', 'cross-setup rejected', 'demo pairing bypass rejected'], revision: ack.revision };
writeFileSync('tmp/blender-integration/api-report.json', JSON.stringify(report, null, 2));
console.log(JSON.stringify(report));
